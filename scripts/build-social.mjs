import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const icon = "public/icons/icon-512-v5.png";
const digest = createHash("sha256")
  .update(readFileSync(root + icon))
  .digest("hex");
mkdirSync(root + "public/social", { recursive: true });
const result = spawnSync(
  "magick",
  [
    "-size",
    "1200x630",
    "xc:#ffffff",
    "-fill",
    "#ff634c",
    "-draw",
    "rectangle 0,0 1199,15",
    "-stroke",
    "#d8dee2",
    "-draw",
    "line 72,501 1128,501",
    "-stroke",
    "none",
    "(",
    icon,
    "-resize",
    "128x128",
    "(",
    "-size",
    "128x128",
    "xc:none",
    "-fill",
    "white",
    "-draw",
    "roundrectangle 0,0 127,127 18,18",
    ")",
    "-alpha",
    "off",
    "-compose",
    "CopyOpacity",
    "-composite",
    ")",
    "-geometry",
    "+1000+470",
    "-compose",
    "Over",
    "-composite",
    "-fill",
    "#263f50",
    "-font",
    "node_modules/@fontsource/bebas-neue/files/bebas-neue-latin-400-normal.woff",
    "-pointsize",
    "54",
    "-annotate",
    "+72+582",
    "LOCDOC.",
    "-font",
    "assets/social/Mono-SemiBold.ttf",
    "-pointsize",
    "82",
    "-fill",
    "#252b31",
    "-annotate",
    "+72+140",
    "Local Markdown.",
    "-annotate",
    "+72+232",
    "Shared ideas.",
    "-font",
    "assets/social/Mono-Regular.ttf",
    "-pointsize",
    "37",
    "-fill",
    "#353d45",
    "-annotate",
    "+72+338",
    "Write together.",
    "-annotate",
    "+72+396",
    "Keep your files.",
    "-font",
    "assets/social/Body-Regular.ttf",
    "-pointsize",
    "29",
    "-fill",
    "#66737d",
    "-annotate",
    "+286+578",
    "Local Markdown",
    "-set",
    "comment",
    `Locdoc social preview v4: complete first document study, with its white background, JetBrains Mono typography, graphite/rust text, left wordmark and filename, full lower-right Origami Hash, plus the requested orange top rule. Original layout rendered by scripts/build-social.mjs with ImageMagick; existing icon ${icon}, SHA-256 ${digest}. Self-hosted JetBrains Mono, Bebas Neue and IBM Plex Sans. 1200x630px.`,
    "-depth",
    "8",
    "-define",
    "png:compression-level=9",
    "-define",
    "png:exclude-chunks=date,time",
    "public/social/locdoc-v4.png",
  ],
  { cwd: root, encoding: "utf8" },
);
if (result.error)
  throw new Error("Install ImageMagick to regenerate the social preview.", {
    cause: result.error,
  });
if (result.status !== 0) throw new Error(result.stderr);
console.log("public/social/locdoc-v4.png");
