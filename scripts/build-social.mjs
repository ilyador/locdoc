import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const icon = "public/icons/icon-512-v5.png";
const digest = createHash("sha256")
  .update(readFileSync(root + icon))
  .digest("hex");
mkdirSync(root + "public/social", { recursive: true });
const result = spawnSync(
  "magick",
  [
    "-size",
    "1200x630",
    "xc:#fcfcfa",
    "-fill",
    "#ff634c",
    "-draw",
    "rectangle 0,0 1199,15",
    "-stroke",
    "#cbd3d6",
    "-draw",
    "line 72,445 1128,445",
    "-stroke",
    "none",
    "(",
    icon,
    "-resize",
    "104x104",
    "(",
    "-size",
    "104x104",
    "xc:none",
    "-fill",
    "white",
    "-draw",
    "roundrectangle 0,0 103,103 14,14",
    ")",
    "-alpha",
    "off",
    "-compose",
    "CopyOpacity",
    "-composite",
    ")",
    "-geometry",
    "+72+477",
    "-compose",
    "Over",
    "-composite",
    "-fill",
    "#263f50",
    "-font",
    "node_modules/@fontsource/bebas-neue/files/bebas-neue-latin-400-normal.woff",
    "-pointsize",
    "62",
    "-annotate",
    "+204+559",
    "LOCDOC.",
    "-font",
    "assets/social/Mono-SemiBold.ttf",
    "-pointsize",
    "92",
    "-fill",
    "#252b31",
    "-annotate",
    "+72+145",
    "Local Markdown.",
    "-annotate",
    "+72+245",
    "Shared ideas.",
    "-font",
    "assets/social/Mono-Regular.ttf",
    "-pointsize",
    "39",
    "-fill",
    "#353d45",
    "-annotate",
    "+72+329",
    "Write together.",
    "-annotate",
    "+72+382",
    "Keep your files.",
    "-font",
    "assets/social/Body-Regular.ttf",
    "-pointsize",
    "31",
    "-fill",
    "#66737d",
    "-annotate",
    "+832+551",
    "Local Markdown",
    "-set",
    "comment",
    `Locdoc social preview v3: user-approved combination of the first study's JetBrains Mono and graphite/rust text with the third study's orange top rule, paper layout and full logo footer. Original layout rendered by scripts/build-social.mjs with ImageMagick; existing Origami Hash icon ${icon}, SHA-256 ${digest}. Self-hosted JetBrains Mono, Bebas Neue and IBM Plex Sans. 1200x630px.`,
    "-depth",
    "8",
    "-define",
    "png:compression-level=9",
    "-define",
    "png:exclude-chunks=date,time",
    "public/social/locdoc-v3.png",
  ],
  { cwd: root, encoding: "utf8" },
);
if (result.error)
  throw new Error("Install ImageMagick to regenerate the social preview.", {
    cause: result.error,
  });
if (result.status !== 0) throw new Error(result.stderr);
console.log("public/social/locdoc-v3.png");
